/** Standard display date format: e.g. 20th April 2000 */
export const DISPLAY_DATE_FORMAT = "do MMMM yyyy"

/** Date with time: e.g. 20th April 2000 · 02:30 PM */
export const DISPLAY_DATE_TIME_FORMAT = "do MMMM yyyy · hh:mm a"

/** Date with "at" time: e.g. 20th April 2000 at 02:30 PM */
export const DISPLAY_DATE_AT_TIME_FORMAT = "do MMMM yyyy 'at' hh:mm a"

/** Weekday with date: e.g. Monday, 20th April 2000 */
export const DISPLAY_DAY_DATE_FORMAT = "EEEE, do MMMM yyyy"
